"""
circuits.py -- where each gross code memory circuit comes from.

What this file is FOR (plain words):
    The whole check compares two independently-written versions of the same
    experiment -- a 12-round Z-basis memory on the [[144,12,12]] gross code --
    under the same physical error rate p:

      * "ibm"  : IBM's own Stim circuit, shipped as test data in IBM's Relay-BP
                 repository (github.com/trmue/relay, tests/testdata/...), copied
                 into data/ibm_circuits/ (see data/README.md).
                 We treat this as the reference ("IBM's actual thing").
      * "sq"   : the circuit generated by the third-party `stabilizer-qec`
                 package (BivariateBicycleCode("gross").memory_circuit).

    Both are returned as plain `stim.Circuit` objects so that every later step
    (error model, decoder, sampling) is identical for the two.
"""

from pathlib import Path

import stim
import stabilizer_qec as sq

# IBM's circuits live in data/ibm_circuits/ (one folder above helpers/).
IBM_DIR = Path(__file__).resolve().parent.parent / "data" / "ibm_circuits"   # helpers/ -> ../data/


def ibm_gross_memory_z(p: float) -> stim.Circuit:
    """Load IBM's gross code Z-memory circuit (12 rounds) at physical error rate p.

    IBM only ships files for a fixed list of p values (0.001 ... 0.01), so we
    look the file up by name and fail loudly if that p is not available.
    """
    path = IBM_DIR / f"gross_memory_Z_p{p}.stim"
    if not path.exists():
        have = sorted(f.name for f in IBM_DIR.glob("*.stim"))
        raise FileNotFoundError(f"no IBM circuit for p={p}; available: {have}")
    return stim.Circuit.from_file(str(path))


def sq_gross_memory_z(p: float, rounds: int = 12) -> stim.Circuit:
    """Build stabilizer-qec's gross code memory circuit and convert it to Stim.

    stabilizer-qec prints its circuits in Stim's text format, so `str(...)`
    followed by `stim.Circuit(...)` gives an exact Stim copy.
    The package's default basis is Z (observables = the 12 logical Z's).
    """
    gross = sq.BivariateBicycleCode("gross")
    return stim.Circuit(str(gross.memory_circuit(rounds, p)))


def surface_memory_z(d: int, p: float, rounds: int | None = None) -> stim.Circuit:
    """Stim's built-in rotated surface code Z-memory with uniform circuit noise.

    Same style of noise as IBM's "uniform_circuit": every gate, reset,
    measurement and idle step fails with probability p.
    One patch = one logical qubit; we compare 12 patches to one gross block.
    """
    rounds = d if rounds is None else rounds
    return stim.Circuit.generated(
        "surface_code:rotated_memory_z",
        distance=d,
        rounds=rounds,
        after_clifford_depolarization=p,       # 2-qubit gate noise
        before_round_data_depolarization=p,    # idle noise on data each round
        before_measure_flip_probability=p,     # measurement errors
        after_reset_flip_probability=p,        # reset errors
    )
